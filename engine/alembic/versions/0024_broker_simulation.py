def _install_broker_guards() -> None:
    for table_name in _BROKER_TABLES:
        op.execute(
            f"CREATE TRIGGER trg_{table_name}_created_at_immutable "
            f"BEFORE UPDATE ON {table_name} FOR EACH ROW "
            "EXECUTE FUNCTION nexus_prevent_created_at_change()"
        )
    op.execute(
        """
        CREATE FUNCTION nexus_broker_binding_guard() RETURNS trigger AS $$
        BEGIN
          IF TG_OP = 'UPDATE' AND OLD.locked AND NOT NEW.locked AND
             (NEW.reconciliation_status <> 'matched' OR NEW.last_reconciled_at IS NULL) THEN
            RAISE EXCEPTION 'broker account unlock requires matched reconciliation'
              USING ERRCODE = 'P3L02';
          END IF;
          RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    op.execute(
        "CREATE TRIGGER trg_broker_binding_guard BEFORE UPDATE ON broker_account_bindings "
        "FOR EACH ROW EXECUTE FUNCTION nexus_broker_binding_guard()"
    )
    op.execute(
        """
        CREATE FUNCTION nexus_broker_command_guard() RETURNS trigger AS $$
        DECLARE binding_locked boolean; binding_reconciliation varchar;
        BEGIN
          SELECT locked, reconciliation_status
            INTO binding_locked, binding_reconciliation
            FROM broker_account_bindings WHERE id = NEW.account_binding_id FOR UPDATE;
          IF TG_OP = 'INSERT' AND
             (binding_locked OR binding_reconciliation <> 'matched') THEN
            RAISE EXCEPTION 'broker account is not reconciled for a new command'
              USING ERRCODE = 'P3L01';
          END IF;
          IF NEW.status = 'sending' AND
             (binding_locked OR binding_reconciliation <> 'matched') THEN
            RAISE EXCEPTION 'broker account is locked for dispatch'
              USING ERRCODE = 'P3L01';
          END IF;
          IF TG_OP = 'UPDATE' AND OLD.status IN
             ('acknowledged','rejected','transport_failed','reconciled',
              'reconciliation_required') AND NEW.status <> OLD.status THEN
            RAISE EXCEPTION 'terminal broker command cannot transition'
              USING ERRCODE = 'P3S01';
          END IF;
          IF TG_OP = 'UPDATE' AND OLD.status = 'result_unknown' AND
             NEW.status NOT IN ('result_unknown','reconciled','reconciliation_required') THEN
            RAISE EXCEPTION 'unknown broker command cannot be resent'
              USING ERRCODE = 'P3S01';
          END IF;
          RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    op.execute(
        "CREATE TRIGGER trg_broker_command_guard BEFORE INSERT OR UPDATE "
        "ON broker_commands FOR EACH ROW EXECUTE FUNCTION nexus_broker_command_guard()"
    )
    op.execute(
        """
        CREATE FUNCTION nexus_broker_event_insert_guard() RETURNS trigger AS $$
        DECLARE expected_sequence bigint;
        BEGIN
          PERFORM 1 FROM broker_account_bindings
            WHERE id = NEW.account_binding_id FOR UPDATE;
          SELECT COALESCE(MAX(event_sequence), 0) + 1 INTO expected_sequence
            FROM broker_order_events
            WHERE account_binding_id = NEW.account_binding_id;
          IF NEW.event_sequence <> expected_sequence THEN
            RAISE EXCEPTION 'broker order event sequence is not monotonic'
              USING ERRCODE = 'P3E01';
          END IF;
          RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    op.execute(
        "CREATE TRIGGER trg_broker_event_insert_guard BEFORE INSERT ON broker_order_events "
        "FOR EACH ROW EXECUTE FUNCTION nexus_broker_event_insert_guard()"
    )
    op.execute(
        """
        CREATE FUNCTION nexus_broker_event_immutable() RETURNS trigger AS $$
        BEGIN
          RAISE EXCEPTION 'broker order events are immutable' USING ERRCODE = 'P3E02';
        END;
        $$ LANGUAGE plpgsql
        """
    )
    op.execute(
        "CREATE TRIGGER trg_broker_event_immutable BEFORE UPDATE OR DELETE "
        "ON broker_order_events FOR EACH ROW EXECUTE FUNCTION nexus_broker_event_immutable()"
    )


def _drop_broker_guards() -> None:
    op.execute("DROP TRIGGER trg_broker_event_immutable ON broker_order_events")
    op.execute("DROP FUNCTION nexus_broker_event_immutable()")
    op.execute("DROP TRIGGER trg_broker_event_insert_guard ON broker_order_events")
    op.execute("DROP FUNCTION nexus_broker_event_insert_guard()")
    op.execute("DROP TRIGGER trg_broker_command_guard ON broker_commands")
    op.execute("DROP FUNCTION nexus_broker_command_guard()")
    op.execute("DROP TRIGGER trg_broker_binding_guard ON broker_account_bindings")
    op.execute("DROP FUNCTION nexus_broker_binding_guard()")
    for table_name in reversed(_BROKER_TABLES):
        op.execute(f"DROP TRIGGER trg_{table_name}_created_at_immutable ON {table_name}")


def _refuse_populated_downgrade() -> None:
    union = " UNION ALL ".join(f"SELECT 1 FROM {table_name}" for table_name in _BROKER_TABLES)
    op.execute(
        "DO $$ BEGIN IF EXISTS (" + union + ") THEN "
        "RAISE EXCEPTION 'broker simulation facts prevent downgrade' "
        "USING ERRCODE = 'P3D01'; END IF; END $$"
    )
