function collectSchemaClosure(schemas, rootNames) {
  const selected = new Set(rootNames);
  const pending = [...rootNames];
  while (pending.length > 0) {
    const name = pending.shift();
    const schema = schemas[name];
    if (!schema) throw new Error(`Runtime schema ${name} is missing`);
    visitSchema(schema, (reference) => {
      const prefix = "#/components/schemas/";
      if (!reference.startsWith(prefix)) throw new Error(`Unsupported runtime schema reference: ${reference}`);
      const referencedName = reference.slice(prefix.length);
      if (!Object.hasOwn(schemas, referencedName)) throw new Error(`Runtime schema reference ${referencedName} is missing`);
      if (!selected.has(referencedName)) {
        selected.add(referencedName);
        pending.push(referencedName);
      }
    });
  }
  return Object.fromEntries([...selected].sort().map((name) => [name, schemas[name]]));
}

function visitSchema(value, visitReference) {
  if (Array.isArray(value)) {
    for (const item of value) visitSchema(item, visitReference);
    return;
  }
  if (!value || typeof value !== "object") return;
  if (typeof value.$ref === "string") visitReference(value.$ref);
  for (const item of Object.values(value)) visitSchema(item, visitReference);
}

function mismatch(path, expected) {
  if (!existsSync(path)) return [`- missing ${path.slice(projectRoot.length + 1)}`];
  return readFileSync(path, "utf8") === expected
    ? []
    : [`- stale ${path.slice(projectRoot.length + 1)}`];
}

function normalize(value) {
  return `${value.replaceAll("\r\n", "\n").trimEnd()}\n`;
}

function writeTarget(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
}
